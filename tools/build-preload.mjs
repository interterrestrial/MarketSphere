/**
 * Bundles the preload script.
 *
 * A sandboxed preload (`sandbox: true`) runs in a restricted module loader
 * that can resolve `electron` and Node builtins but *not* relative files —
 * `require("./lib/navigation-policy")` fails with "module not found" and the
 * bridge silently never appears on the page. Bundling inlines the policy
 * module so the preload keeps working while the sandbox stays on, and keeps
 * one source of truth for the URL rules shared with the main process.
 *
 * `electron` stays external: it is provided by the runtime, not by npm.
 *
 * Run: npm run electron:bundle
 */
import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const result = await build({
  entryPoints: [join(root, "electron/preload.js")],
  outfile: join(root, "electron/dist/preload.js"),
  bundle: true,
  platform: "node",
  target: "node20",
  format: "cjs",
  external: ["electron"],
  // The shell must not depend on the user's Node version at runtime.
  banner: {
    js: "// Generated by tools/build-preload.mjs — do not edit. Source: electron/preload.js",
  },
  minify: false,
  legalComments: "none",
});

if (result.errors.length > 0) process.exit(1);
console.log("Bundled preload -> electron/dist/preload.js");
