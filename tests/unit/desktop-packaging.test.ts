import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import pkg from "../../package.json";

/**
 * The desktop app is a window onto the web application. The single most
 * important property is that no server credential can reach the user's
 * machine, and the second that the renderer stays isolated from Node. Both are
 * configuration rather than logic, so they are asserted here — a change that
 * silently ships the database connection string to every desktop user would
 * otherwise pass review unnoticed.
 */

const root = join(__dirname, "..", "..");
const read = (relative: string) => readFileSync(join(root, relative), "utf8");

const mainSource = read("electron/main.js");
const preloadSource = read("electron/preload.js");

/** Shape of the `build` block electron-builder reads from package.json. */
interface MacTarget {
  target: string;
  arch: string[];
}
interface BuildConfig {
  files: string[];
  afterSign: string;
  mac: {
    target: MacTarget[];
    hardenedRuntime: boolean;
    gatekeeperAssess: boolean;
    category: string;
    entitlements: string;
    entitlementsInherit: string;
    afterSign: string;
  };
}

const build = (pkg as unknown as { build: BuildConfig }).build;

describe("no server secrets reach the desktop app", () => {
  it("ships no database or credential handling in the shell", () => {
    for (const file of [
      "electron/main.js",
      "electron/preload.js",
      "electron/lib/navigation-policy.js",
    ]) {
      const source = read(file);
      for (const forbidden of [
        "DATABASE_URL",
        "AUTH_SECRET",
        "DIRECT_DATABASE_URL",
        "prisma",
        "@prisma/client",
        "neon.tech",
        "postgres://",
        "postgresql://",
        "bcrypt",
        "passwordHash",
      ]) {
        expect(source, `${file} must not reference ${forbidden}`).not.toContain(forbidden);
      }
    }
  });

  it("excludes the database, the server code and every .env file from the bundle", () => {
    const files: string[] = build.files;
    // Only the shell and its manifest are packaged, listed explicitly so an
    // unexpected file has to be added deliberately.
    for (const required of [
      "electron/main.js",
      "electron/preload.js",
      "electron/dist/preload.js",
      "electron/lib/navigation-policy.js",
      "package.json",
    ]) {
      expect(files, `${required} must be packaged`).toContain(required);
    }
    expect(files).not.toContain("electron/**/*");
    // The server stack and credentials must never be included.
    expect(files).toContain("!node_modules/**/*");
    expect(files).toContain("!.env");
    expect(files).toContain("!.env.*");
    for (const forbidden of ["src/**/*", "prisma/**/*", "tests/**/*", "docs/**/*"]) {
      expect(files, `${forbidden} must not be packaged`).not.toContain(forbidden);
    }
  });

  it("ships a bundled preload, because a sandboxed preload cannot require relative modules", () => {
    // Verified the hard way: the first packaged build logged
    // "module not found: ./lib/navigation-policy" and the bridge silently
    // never appeared on the page. The bundle inlines the policy module.
    const bundled = read("electron/dist/preload.js");
    expect(bundled).toContain("Generated by tools/build-preload.mjs");
    // Inlined rather than required at runtime.
    expect(bundled).not.toMatch(/require\("\.\/lib\/navigation-policy"\)/);
    expect(mainSource).toMatch(/require\.resolve\("\.\/dist\/preload\.js"\)/);
    expect(build.files).toContain("electron/dist/preload.js");
  });

  it("requires nothing beyond the Electron runtime", () => {
    // The web app and the shell share one package.json, so `dependencies`
    // legitimately lists Prisma, bcrypt and the rest for the *web* build.
    // What must stay true is that the shell itself imports none of it —
    // otherwise the node_modules exclusion above would break the app.
    const requires = [...mainSource.matchAll(/require\(["']([^"']+)["']\)/g)].map((m) => m[1]);
    const external = requires.filter((name) => !name.startsWith(".") && name !== "electron");
    expect(external, `shell must not require ${external.join(", ")}`).toEqual([]);

    const preloadRequires = [...preloadSource.matchAll(/require\(["']([^"']+)["']\)/g)].map(
      (m) => m[1]
    );
    // A relative require is legal in the source but impossible in a sandboxed
    // preload, which is exactly why the bundle step exists.
    expect(preloadRequires.filter((name) => !name.startsWith(".") && name !== "electron")).toEqual(
      []
    );
  });
});

describe("renderer isolation", () => {
  it("keeps the page away from Node", () => {
    expect(mainSource).toMatch(/contextIsolation:\s*true/);
    expect(mainSource).toMatch(/nodeIntegration:\s*false/);
    expect(mainSource).toMatch(/sandbox:\s*true/);
    expect(mainSource).toMatch(/webviewTag:\s*false/);
    expect(mainSource).toMatch(/allowRunningInsecureContent:\s*false/);
    expect(mainSource).toMatch(/webSecurity:\s*true/);
  });

  it("exposes a single, frozen, minimal API to the page", () => {
    expect(preloadSource).toMatch(/contextBridge\.exposeInMainWorld/);
    // One namespace, and it is frozen so the page cannot add to it.
    const exposed = preloadSource.match(/exposeInMainWorld\(([^,]+),/g) ?? [];
    expect(exposed).toHaveLength(1);
    expect(preloadSource).toMatch(/Object\.freeze/);
    // The raw bridge must never be handed to the page.
    expect(preloadSource).not.toMatch(/exposeInMainWorld\([^)]*ipcRenderer/);
    expect(preloadSource).not.toMatch(
      /exposeInMainWorld\(\s*["'][^"']+["']\s*,\s*\{\s*ipcRenderer/
    );
  });

  it("validates every URL the page can ask to open", () => {
    expect(preloadSource).toMatch(/isBlockedUrl/);
    expect(preloadSource).toMatch(/sanitizeExternalUrl/);
  });

  it("denies developer tools outside development", () => {
    expect(mainSource).toMatch(/\.\.\.\(isDev \? \[\{ role: "toggleDevTools" \}\] : \[\]\)/);
  });

  it("treats a TLS failure as fatal", () => {
    // Ignoring certificate errors would hide MITM attempts from the user.
    expect(mainSource).toMatch(/setCertificateVerifyProc/);
    expect(mainSource).not.toMatch(/certificate-error.*ignoreCertificateErrors:\s*true/);
    expect(mainSource).toMatch(/callback\(request\.errorCode === 0 \? 0 : -2\)/);
  });
});

describe("macOS packaging", () => {
  it("produces an unsigned demo dmg", () => {
    const mac = build.mac;
    const targets = mac.target.map((entry) => entry.target);
    expect(targets).toContain("dmg");
    expect(mac.identity).toBeNull();
    expect(mac.hardenedRuntime).toBe(false);
    expect(mac.gatekeeperAssess).toBe(false);
    expect(mac.category).toBe("public.app-category.business");
  });

  it("does not invoke signing or notarization for the demo build", () => {
    expect(build.mac.notarize).toBe(false);
    expect(build.afterSign).toBeUndefined();
  });

  it("requests no entitlement beyond network access and JIT", () => {
    // A camera, microphone or file-access entitlement would be scope creep
    // for an app that renders a marketplace.
    const entitlements = read("packaging/entitlements.mac.plist");
    expect(entitlements).toContain("com.apple.security.network.client");
    for (const forbidden of [
      "com.apple.security.device.camera",
      "com.apple.security.device.audio-input",
      "com.apple.security.device.location",
      "com.apple.security.files.user-selected.read-write",
    ]) {
      expect(entitlements).not.toContain(forbidden);
    }
  });

  it("points at the deployed web app rather than localhost", () => {
    const policy = read("electron/lib/navigation-policy.js");
    expect(policy).toContain("https://market-sphere-one.vercel.app");
    expect(policy).toContain("http://localhost:3000");
  });
});
